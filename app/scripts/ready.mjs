// Writes src/data/ready.js: the list of lesson IDs that have content. Runs before dev/build.
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.join(here, '..', 'src', 'lessons');
const ids = [];
for (const f of fs.readdirSync(dir).filter(f => f.endsWith('.js')).sort()) {
  try { const m = await import(pathToFileURL(path.join(dir, f)).href); ids.push(...Object.keys(m.default || {})); }
  catch (e) { console.warn(`ready.mjs: skipped ${f}: ${e.message}`); }
}
fs.writeFileSync(path.join(here, '..', 'src', 'data', 'ready.js'), `// Generated by scripts/ready.mjs\nexport const READY = new Set(${JSON.stringify(ids.sort())});\n`);
console.log(`ready.mjs: ${ids.length} lessons with content`);
