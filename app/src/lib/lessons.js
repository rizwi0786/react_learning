// Lesson data lives in src/lessons/<CODE>.js or <CODE>.N.js. Each module's files load on demand
// (one network chunk per file), so the first page stays small.
const files = import.meta.glob('../lessons/*.js');
const byModule = {};
for (const [path, load] of Object.entries(files)) {
  const code = path.split('/').pop().split('.')[0];
  (byModule[code] ||= []).push(load);
}

const cache = new Map();
export function loadModule(code) {
  if (!cache.has(code)) {
    const loaders = byModule[code] || [];
    cache.set(code, Promise.all(loaders.map(l => l())).then(mods => Object.assign({}, ...mods.map(m => m.default))));
  }
  return cache.get(code);
}

// Which IDs are written, without loading every module: filled in as modules load,
// plus a build-time list in data/ready.js (regenerated by scripts/ready.mjs).
export const hasModuleFiles = code => !!byModule[code];
